import type { IssueTexts } from '../data/issues.ts';
import type { BandSort, ThemePreference } from '../model.ts';
import type { RegionId } from '../view/mapRegions.ts';
import type { TimePreset } from '../view/timePresets.ts';

type Text = string;
type Count = (count: number) => string;

/** Statuses as shown on a show; "played" is a past show that took place. */
export type StatusKind = 'scheduled' | 'cancelled' | 'postponed' | 'soldout' | 'played';
export type SearchGroup = 'band' | 'tag' | 'place' | 'venue' | 'tour' | 'event';
export type SidebarList = 'bands' | 'places' | 'genres' | 'previews';

/** Every text the interface shows. Band data (names, venues, tours, notes) is never translated. */
export interface Messages {
  readonly page: {
    readonly skipLink: Text;
    readonly homeTitle: Text;
    readonly settings: Text;
    readonly sourceCode: Text;
    readonly sidebar: Text;
    readonly lists: Text;
    readonly tabBands: Text;
    readonly tabPlaces: Text;
    readonly tabGenres: Text;
    readonly selectedShows: Text;
    readonly previewedFiles: Text;
    readonly mapAndTimeline: Text;
    readonly mapControls: Text;
    readonly timelineControls: Text;
    readonly footerSources: Text;
    readonly footerPrivacy: Text;
    readonly dropFiles: Text;
    readonly sidebarToggle: (visible: number, total: number) => string;
  };
  readonly shows: Count;
  readonly bands: Count;
  readonly noShowsInRange: Text;
  readonly status: Readonly<Record<StatusKind, string>>;
  readonly search: {
    readonly placeholder: Text;
    readonly label: Text;
    readonly clear: Text;
    readonly results: Count;
    readonly resultsLabel: Text;
    readonly nothingMatches: (query: string) => string;
    readonly groups: Readonly<Record<SearchGroup, string>>;
    readonly showsAndBands: (shows: number, bands: number) => string;
    readonly genreBands: Count;
  };
  readonly bandList: {
    readonly filter: Text;
    readonly filterLabel: Text;
    readonly clearFilter: Text;
    readonly sortLabel: Text;
    readonly sorts: Readonly<Record<BandSort, string>>;
    readonly showAll: Text;
    readonly hideAll: Text;
    readonly shownCount: (visible: number, total: number) => string;
    readonly listShown: Text;
    readonly listShownLabel: Count;
    readonly openPreviews: Count;
    readonly tickedGenres: Count;
    readonly showAllGenres: Text;
    readonly noBands: Text;
    readonly noBandForGenres: Text;
    readonly noMatch: (query: string) => string;
    readonly quietToggle: (open: boolean, count: number) => string;
    readonly previewBadge: Text;
    readonly showOnMap: (band: string) => string;
    readonly listDates: (band: string) => string;
  };
  readonly placeList: {
    readonly filter: Text;
    readonly clearFilter: Text;
    readonly summary: (cities: number, countries: number) => string;
    readonly empty: Text;
    readonly noMatch: (query: string) => string;
    readonly showCities: (country: string) => string;
    readonly hideCities: (country: string) => string;
    readonly showsAndBands: (shows: number, bands: number) => string;
    readonly andMore: (first: string, more: number) => string;
  };
  readonly genreList: {
    readonly filter: Text;
    readonly clearFilter: Text;
    readonly hint: Text;
    readonly showing: Count;
    readonly showAll: Text;
    readonly noMatch: (query: string) => string;
    readonly noGenre: Text;
    readonly bandsAndShows: (bands: number, shows: number) => string;
    readonly showOnMap: (genre: string) => string;
    readonly listDates: (genre: string) => string;
  };
  readonly selection: {
    readonly back: Readonly<Record<SidebarList, string>>;
    readonly allDates: Text;
    readonly between: (start: string, end: string) => string;
    readonly live: (shows: number, range: string) => string;
    readonly emptyNamed: (name: string, range: string) => string;
    readonly emptyBands: (range: string) => string;
    readonly emptyPlace: (place: string, range: string) => string;
    readonly hiddenPicked: Text;
    readonly pickedOne: (band: string, city: string) => string;
    readonly pickedInCity: (shows: number, city: string, band: string | null) => string;
    readonly pickedInCities: (shows: number, cities: number, band: string | null) => string;
    readonly moreNotListed: Count;
    readonly announce: (title: string, shows: number) => string;
    readonly replayTour: Text;
    readonly venueUnknown: Text;
    readonly starts: (time: string) => string;
    readonly until: (date: string) => string;
    readonly tickets: Text;
    readonly source: Text;
    readonly pinVenue: Text;
    readonly pinCity: Text;
  };
  readonly timeline: {
    readonly today: Text;
    readonly cursor: Text;
    readonly noBandsShown: Text;
    readonly noShowsInWindow: Text;
    readonly hiddenLanes: Count;
    readonly showAllLanes: Text;
    readonly dot: (band: string, date: string, city: string, status: string | null) => string;
    readonly presets: Readonly<Record<TimePreset, { readonly label: string; readonly short: string }>>;
    readonly customRange: Text;
    readonly timeRange: Text;
    readonly earlier: Text;
    readonly zoomOut: Text;
    readonly later: Text;
    readonly moveRange: Text;
    readonly options: Text;
    readonly optionsTitle: Text;
    readonly follow: { readonly label: Text; readonly note: Text };
    readonly hideEmpty: { readonly label: Text; readonly note: Text };
    readonly pastMonth: { readonly label: Text; readonly note: Text };
    readonly help: Text;
    readonly helpLines: readonly Text[];
  };
  readonly map: {
    readonly surface: Text;
    readonly cursor: Text;
    readonly zoomIn: Text;
    readonly zoomOut: Text;
    readonly fit: Text;
    readonly area: Text;
    readonly areaMenu: Text;
    readonly nearMe: Text;
    readonly regions: Text;
    readonly regionNames: Readonly<Record<RegionId, string>>;
    readonly km: Count;
    readonly asGlobe: Text;
    readonly asFlat: Text;
    readonly listNearby: Text;
    readonly nearby: (shows: number, km: number) => string;
    readonly locating: Text;
    readonly locationUnsupported: Text;
    readonly locationDenied: Text;
    readonly locationFailed: Text;
    readonly pin: (shows: number, place: string, listed: readonly string[], more: number) => string;
  };
  readonly tooltip: {
    readonly showsIn: (shows: number, place: string) => string;
    readonly moreShows: Count;
    readonly moreBands: Count;
    readonly bandSummary: (shows: number, upcoming: boolean, date: string) => string;
  };
  readonly settings: {
    readonly title: Text;
    readonly theme: Text;
    readonly themes: Readonly<Record<ThemePreference, string>>;
    readonly language: Text;
    readonly automatic: Text;
    readonly timeFormat: Text;
    readonly clock12: Text;
    readonly clock24: Text;
    readonly files: Text;
    readonly previewFiles: Text;
    readonly exportAll: Text;
    readonly reloadLosesPreviews: Text;
  };
  readonly preview: {
    readonly title: Count;
    readonly note: Text;
    readonly removeAll: Text;
    readonly remove: Text;
    readonly download: Text;
    readonly geocodeHint: (file: string) => string;
    readonly commitHint: (file: string) => string;
    readonly unusable: Text;
    readonly usable: (usable: number, total: number, rowsLeftOut: boolean) => string;
    readonly statuses: { readonly valid: Text; readonly partial: Text; readonly invalid: Text };
    readonly errors: Count;
    readonly warnings: Count;
    readonly newBand: Count;
    readonly bandChanged: (fields: string) => string;
    readonly added: Text;
    readonly removed: Text;
    readonly changed: Text;
    readonly compared: (added: number, removed: number, changed: number, unchanged: number) => string;
    readonly noDifferences: Text;
    readonly moreNotListed: Count;
    readonly moreIssues: Count;
  };
  readonly issues: IssueTexts;
}
