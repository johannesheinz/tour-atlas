const value: IssueTexts['value'] = (described) => {
  switch (described.kind) {
    case 'literal':
      return described.text;
    case 'null':
      return 'null';
    case 'nothing':
      return 'nada';
    case 'list':
      return 'una lista';
    case 'object':
      return 'un objeto';
  }
};

