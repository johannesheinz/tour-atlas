const value: IssueTexts['value'] = (described) => {
  switch (described.kind) {
    case 'literal':
      return described.text;
    case 'null':
      return 'null';
    case 'nothing':
      return 'nihil';
    case 'list':
      return 'index';
    case 'object':
      return 'obiectum';
  }
};

