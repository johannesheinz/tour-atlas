const value: IssueTexts['value'] = (described) => {
  switch (described.kind) {
    case 'literal':
      return described.text;
    case 'null':
      return 'null';
    case 'nothing':
      return 'ei mitään';
    case 'list':
      return 'lista';
    case 'object':
      return 'objekti';
  }
};

