const value: IssueTexts['value'] = (described) => {
  switch (described.kind) {
    case 'literal':
      return described.text;
    case 'null':
      return 'null';
    case 'nothing':
      return 'ingenting';
    case 'list':
      return 'en lista';
    case 'object':
      return 'ett objekt';
  }
};

