const value: IssueTexts['value'] = (described) => {
  switch (described.kind) {
    case 'literal':
      return described.text;
    case 'null':
      return 'null';
    case 'nothing':
      return 'nenio';
    case 'list':
      return 'listo';
    case 'object':
      return 'objekto';
  }
};

