const value: IssueTexts['value'] = (described) => {
  switch (described.kind) {
    case 'literal':
      return described.text;
    case 'null':
      return 'null';
    case 'nothing':
      return 'rien';
    case 'list':
      return 'une liste';
    case 'object':
      return 'un objet';
  }
};

