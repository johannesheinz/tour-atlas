const value: IssueTexts['value'] = (described) => {
  switch (described.kind) {
    case 'literal':
      return described.text;
    case 'null':
      return 'null';
    case 'nothing':
      return 'nichts';
    case 'list':
      return 'eine Liste';
    case 'object':
      return 'ein Objekt';
  }
};

